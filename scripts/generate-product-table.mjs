// -----------------------------------------------------------------------------
// Builds src/insteon/product-table.js from the Insteon product database of
// pyinsteon (pyinsteon/device_types/ipdb.py, MIT, Tom Harris). Development
// only: the script is not in the image, its output is.
//
//   node scripts/generate-product-table.mjs <pyinsteon>/pyinsteon/device_types/ipdb.py
//
// Each entry keeps the category, the sub-category, the description, the model
// and the pyinsteon device class (the integration maps the class to what it
// shows, in src/insteon/products.js).
// -----------------------------------------------------------------------------

import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/generate-product-table.mjs <path to ipdb.py>');
  process.exit(1);
}
const text = readFileSync(source, 'utf8');
const start = text.indexOf('_products = [');
const end = text.indexOf('\n    ]', start);
const body = text.slice(start, end);
const entry =
  /Product\(\s*(None|0x[0-9A-Fa-f]+)\s*,\s*(None|0x[0-9A-Fa-f]+)\s*,\s*(None|0x[0-9A-Fa-f]+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,\s*(\w+)\s*,?\s*\)/g;
const rows = [];
for (const match of body.matchAll(entry)) {
  const [, cat, subcat, , description, model, deviceClass] = match;
  if (cat === 'None' || subcat === 'None') continue;
  rows.push([Number(cat), Number(subcat), description, model, deviceClass]);
}
if (rows.length < 100) throw new Error(`only ${rows.length} products read: wrong file?`);
const lines = rows.map(
  ([cat, subcat, description, model, deviceClass]) =>
    `  [0x${cat.toString(16).padStart(2, '0')}, 0x${subcat.toString(16).padStart(2, '0')}, ${JSON.stringify(description)}, ${JSON.stringify(model)}, ${JSON.stringify(deviceClass)}],`,
);
const out = `// GENERATED by scripts/generate-product-table.mjs from pyinsteon's ipdb.py
// (MIT, Tom Harris): never edit by hand. [category, sub-category, description,
// model, pyinsteon device class].
/* prettier-ignore */
export const PRODUCTS = [
${lines.join('\n')}
];
`;
writeFileSync(new URL('../src/insteon/product-table.js', import.meta.url), out);
console.log(`${rows.length} products written`);
